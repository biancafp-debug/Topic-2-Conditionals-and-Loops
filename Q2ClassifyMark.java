public class Q2ClassifyMark {
    public static void main(String[] args) {
        float mark = 89;
        if (mark >= 70) {
            System.out.println("First Class. YAYY!!!");
        } else if (mark >= 40 && mark <= 69) {
            System.out.println("Pass.");
        } else {
            System.out.println("Fail.");
        }
    }
    
}
